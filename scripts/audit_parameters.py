#!/usr/bin/env python
"""Generate docs/PARAMETER_AUDIT.md from ansg.utils.parameter_audit (deterministic).

Usage (repo root):  python scripts/audit_parameters.py [--check]
--check exits non-zero if the committed document is out of date.
"""

from __future__ import annotations

import sys
from pathlib import Path

from ansg.utils.parameter_audit import (
    BACKBONES, CSAM_HEADS, a25_csam_excerpt_params, bias_matrix_floats, dal_params,
    eq_4_13_generator_params, head_split, sec_4_3_6_pattern_params,
)

OUT = Path("docs/PARAMETER_AUDIT.md")


def render() -> str:
    L: list[str] = []
    w = L.append
    w("# Parameter and shape audit (arithmetic only)\n")
    w("*Generated by `scripts/audit_parameters.py` from `src/ansg/utils/parameter_audit.py`. "
      "No model was downloaded or run. 'public' = documented configuration of a public checkpoint, "
      "not a thesis claim. Conflict ids refer to `SPECIFICATION_CONFLICTS.md`.*\n")

    w("## 1. CSAM head size: `hidden_size // 12` (App. A.25, line 22)\n")
    w("| Backbone | hidden | layers | native heads | head_dim = hidden // 12 | remainder | divides? | source |")
    w("| --- | ---: | ---: | ---: | ---: | ---: | --- | --- |")
    for b in BACKBONES:
        hd, rem = head_split(b.hidden_size, CSAM_HEADS)
        w(f"| {b.name} | {b.hidden_size} | {b.num_layers} | {b.num_heads} | {hd} | {rem} | "
          f"{'yes' if rem == 0 else '**no**'} | {b.source} |")
    w("\nOnly d = 768 gives d_k = 64 (the d_k stated in §4.3.6) with 12 heads. With A.3's hidden size 1280 "
      "the 12 heads cover 12 × 106 = 1,272 of 1,280 dimensions; a reshape to (12, 106) would fail. "
      "The excerpt's helper `compute_multihead_attention` is undefined, so its actual behaviour cannot be "
      "determined (C-CSAM-7).\n")

    w("## 2. DAL (LoRA r = 8, 5 dialects)\n")
    w("| Backbone | 1 adapter/layer (Ch.4 §4.4.1: 2·r·d) | q_proj + v_proj (Table 5.8) |")
    w("| --- | ---: | ---: |")
    for b in BACKBONES:
        w(f"| {b.name} | {dal_params(b.hidden_size, b.num_layers):,} | "
          f"{dal_params(b.hidden_size, b.num_layers, matrices_per_layer=2):,} |")
    w("\nThesis statements: 737,280 / 738K (§4.4.1, Table 4.12), 1.2M (§4.1.6), '0.3%' (Ch.3, §4.9), "
      "2.5M LoRA-only (Table 5.1) (C-MODEL-2, C-DAL-1). Only the gpt2-small shape reproduces 737,280.\n")

    w("## 3. CSAM parameters\n")
    w("| Quantity | Value | Basis |")
    w("| --- | ---: | --- |")
    for hid in (1280, 768):
        p = a25_csam_excerpt_params(hidden_size=hid)
        w(f"| A.25 excerpt, visible modules only, hidden {hid} | {p['total_visible']:,} | "
          f"embedding {p['schema_embeddings']:,} + Q {p['query_proj']:,} + K {p['key_proj']:,} + V {p['value_proj']:,} |")
    w(f"| Schema embeddings 898 × 768 | {898 * 768:,} | §4.6.1 |")
    w(f"| Schema embeddings 1,847 × 256 | {1847 * 256:,} | A.25 |")
    w(f"| W_proj 300 × 768 (no bias stated) | {300 * 768:,} | Eq. 4.8 |")
    w(f"| §4.3.6 pattern vectors b_p ∈ R^64 + w_p, 847 patterns | {sec_4_3_6_pattern_params():,} | §4.3.6 |")
    w(f"| Eq. 4.13 vectors v_(s,i), 898 schemas × 12 heads, **assuming** pos_dim = c_s dim = 768 | "
      f"{eq_4_13_generator_params(898, 12, 768, 768):,} | pos_dim not stated |")
    w("| Thesis: CSAM bias matrices | 16,000,000 | §4.1.6 |")
    w("| Thesis: cultural modules | 73,000,000 | Table 5.1 |")
    w("| Thesis: 'CSAM alone' | 73,000,000 | §8.7.1 |")
    w("\nNone of the computable components reproduces 16M or 73M; the A.25 excerpt accounts for ≈ 2.77M at "
      "hidden 1280. H_i and R_i are recomputed per input from S_active (Eq. 4.12) — §4.6.1 counts them as "
      f"memory ({bias_matrix_floats(512):,} floats at n = 512), so they cannot themselves be the 16M stored "
      "parameters (C-MODEL-2, C-CSAM-2).\n")

    w("## 4. CSAM output combination\n")
    w("App. A.25 returns 0.370·h + 0.347·heritage + 0.283·rhetorical; the coefficients sum to "
      f"{0.370 + 0.347 + 0.283:.3f} (a convex combination of hidden states). Eq. 4.9 instead adds β·H_i + γ·R_i "
      "to pre-softmax attention logits; α = 0.370 does not appear in Ch.4 (C-CSAM-4).\n")
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("up to date" if ok else "docs/PARAMETER_AUDIT.md is stale; rerun without --check")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
