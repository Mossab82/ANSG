#!/usr/bin/env python
"""Synthetic end-to-end smoke test of the integrated ANSG code path (Issue #11).

    Nights text -> ingestion -> ANHC record -> (synthetic) DIA label
    -> CKG activation -> SchemaVocabulary (PAD = 0) -> TrainingExample
    -> NarrativeDataset/collate -> ANSG forward/backward (CSAM + DAL)
    -> generation -> evaluation reported separately (CRAFT refuses CMPI)

Everything is SYNTHETIC: the Nights text, the CKG and the DIA label come from
``tests/fixtures`` (see its README), the model is randomly initialised and
untrained, and the generated bytes are meaningless. The report verifies that the
pieces connect; it is not a dissertation result and contains no metric.

Usage:  python scripts/e2e_smoke.py --output runs/e2e_smoke
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests" / "fixtures"


def run(output_dir: str | Path, seed: int = 42) -> dict:
    import torch

    from ansg.config import ModelConfig
    from ansg.data.nights import ingest_file
    from ansg.data.records import (AnnotationSource, AnnotationStatus, CopyrightStatus,
                                   DialectAnnotation, SourceProvenance)
    from ansg.data.training_dataset import ByteTokenizer, NarrativeDataset, collate
    from ansg.data.training_examples import SchemaVocabulary, build_example, write_examples
    from ansg.evaluation.craft import CraftRegistry, EvaluationSample, MetricNotSpecifiedError
    from ansg.knowledge.ckg import CulturalKnowledgeGraph, LexicalTriggerEvidence
    from ansg.model import ANSG
    from ansg.utils.config import load_yaml_config
    from ansg.utils.provenance import git_revision, sha256_file

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    torch.manual_seed(seed)
    steps: list[dict] = []

    def check(name: str, ok: bool, **detail) -> None:
        steps.append({"step": name, "ok": bool(ok), **detail})
        if not ok:
            raise AssertionError(f"E2E step failed: {name}: {detail}")

    # 1. ingestion (synthetic Nights fixture)
    nights_file = FIXTURES / "nights" / "synthetic_nights.txt"
    prov = SourceProvenance(source_id="synthetic", title="synthetic Nights fixture",
                            copyright_status=CopyrightStatus.PUBLIC_DOMAIN, redistributable=True)
    records, _ = ingest_file(nights_file, prov)
    tales = [r for r in records if r.narrative.title]
    check("ingest", len(tales) == 2, records=len(records), tales=len(tales))

    # 2. explicit (synthetic, automatic) DIA label on one tale only; the other stays unlabelled
    tales[1].dia.append(DialectAnnotation(span=None, annotator_id=None, source=AnnotationSource.AUTOMATIC,
                                          attributes={"synthetic": True}, label="Levantine"))
    tales[1].annotation_status["dia"] = AnnotationStatus.AUTOMATIC
    for i, r in enumerate(tales):
        r.split = "train"

    # 3. CKG activation + schema vocabulary
    ckg_file = FIXTURES / "ckg" / "synthetic_ckg.json"
    graph = CulturalKnowledgeGraph.from_json(ckg_file)
    vocab = SchemaVocabulary.from_graph(graph, source_path=ckg_file)
    examples = [build_example(r, graph, vocab, LexicalTriggerEvidence()) for r in tales]
    check("activation_and_vocabulary", vocab.schema_count == len(graph.nodes) + 1,
          schema_count=vocab.schema_count,
          examples=[{"record_id": e.record_id, "schema_node_ids": list(e.schema_node_ids),
                     "schema_ids": list(e.schema_ids), "dialect": e.dialect,
                     "dialect_reason": e.dialect_reason} for e in examples])
    check("unknowns_stay_unknown", examples[0].dialect_id is None and examples[1].dialect_id == 2,
          dialect_ids=[e.dialect_id for e in examples])

    # 4. training examples -> core dataset
    examples_file = out / "train.examples.jsonl"
    write_examples(examples, examples_file)
    cfg = ModelConfig(context_length=128, schema_count=vocab.schema_count)
    dataset = NarrativeDataset(examples_file, context_length=cfg.context_length)
    batch = collate(dataset.rows)
    check("dataset_and_collate", batch["dialect_ids"].tolist() == [-1, 2],
          input_ids=list(batch["input_ids"].shape), schema_ids=batch["schema_ids"].tolist(),
          schema_mask=batch["schema_mask"].tolist(), dialect_ids=batch["dialect_ids"].tolist())

    # 5. model forward/backward (CSAM + pairwise bias + DAL) and one optimiser step
    model = ANSG(cfg)
    optimiser = torch.optim.AdamW(model.parameters(), lr=1e-3)
    result = model(**batch)
    result["loss"].backward()
    grads_finite = all(torch.isfinite(p.grad).all() for p in model.parameters() if p.grad is not None)
    optimiser.step()
    check("forward_backward", bool(torch.isfinite(result["loss"])) and grads_finite,
          loss_untrained=float(result["loss"].detach()), logits=list(result["logits"].shape))

    # 6. batch invariance: the scheduled tale alone vs. inside the batch
    model.eval()
    with torch.no_grad():
        single = collate([dataset.rows[1]])
        n = len(dataset.rows[1]["tokens"])
        alone = model(**{k: v for k, v in single.items() if k != "labels"})["logits"][0, :n]
        batched = model(**{k: v for k, v in batch.items() if k != "labels"})["logits"][1, :n]
    diff = float((alone - batched).abs().max())
    check("batch_invariance", diff < 1e-4, max_abs_logit_diff=diff)

    # 7. generation (untrained model: bytes are meaningless)
    tokenizer = ByteTokenizer()
    prompt = batch["input_ids"][:, :16]
    generated = model.generate(prompt, batch["schema_ids"], batch["dialect_ids"], max_new_tokens=8,
                               schema_mask=batch["schema_mask"])
    check("generation", list(generated.shape) == [2, 24], shape=list(generated.shape),
          sample_text_meaningless=tokenizer.decode(generated[1, 16:].tolist()))

    # 8. evaluation reported separately: no CRAFT metric is computable
    registry = CraftRegistry.from_config(load_yaml_config(ROOT / "configs" / "evaluation" / "craft.yaml"))
    try:
        registry.get("CMPI")([EvaluationSample("synthetic-0", "نص")])
        refused = False
    except MetricNotSpecifiedError:
        refused = True
    check("evaluation_separate", refused, craft_cmpi="refused (undefined in dissertation, C-EVAL-2)")

    report = {
        "synthetic": True,
        "notice": "SYNTHETIC smoke test of the integrated code path. Untrained model; no dissertation "
                  "result, no metric, no checkpoint produced.",
        "activation_method": "lexical_trigger_count (inspection baseline, not the thesis activation function)",
        "git": git_revision(ROOT),
        "inputs": {str(nights_file.relative_to(ROOT)): sha256_file(nights_file),
                   str(ckg_file.relative_to(ROOT)): sha256_file(ckg_file)},
        "seed": seed,
        "steps": steps,
    }
    (out / "e2e_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return report


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--output", default="runs/e2e_smoke")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args(argv)
    report = run(args.output, args.seed)
    print("SYNTHETIC E2E SMOKE TEST — not a dissertation result")
    for s in report["steps"]:
        print(f"  {'PASS' if s['ok'] else 'FAIL'}  {s['step']}")
    print(f"report: {Path(args.output) / 'e2e_report.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
