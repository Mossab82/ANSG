#!/usr/bin/env python3
"""Build a metadata-only manual review queue for Kalila opening cues.

The queue links each opening cue to its pinned source chapter and neighboring
cue offsets. Neighboring cues are navigation aids only; they are not proposed
story boundaries. No source prose is copied into the queue.
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path
from typing import Any, Iterator


FIELDS = [
    "marker_id", "source_record_id", "source_chapter_title", "source_page_url",
    "source_revision_id", "source_text_sha256", "opening_cue",
    "opening_start_char", "opening_end_char", "previous_opening_start_char",
    "next_opening_start_char", "review_status", "confirmed_narrative_opening",
    "story_end_char", "parent_story_id", "nesting_depth", "DIA", "MOTIF",
    "MORAL", "reviewer_notes",
]


def read_jsonl(path: Path) -> Iterator[dict[str, Any]]:
    with path.open(encoding="utf-8") as stream:
        for line_number, line in enumerate(stream, 1):
            if line.strip():
                try:
                    yield json.loads(line)
                except json.JSONDecodeError as exc:
                    raise ValueError(f"{path}:{line_number}: invalid JSON: {exc}") from exc


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--markers", type=Path, required=True,
                        help="Opening-cue JSONL generated by mark_kalila_nested_story_openings.py")
    parser.add_argument("--sources", type=Path, required=True,
                        help="Pinned source chapter records as JSONL")
    parser.add_argument("--output", type=Path, required=True, help="Metadata-only review CSV")
    parser.add_argument("--report", type=Path, required=True, help="JSON queue summary")
    args = parser.parse_args()

    source_by_id: dict[str, dict[str, Any]] = {}
    for record in read_jsonl(args.sources):
        source_by_id[str(record["record_id"])] = record

    markers = list(read_jsonl(args.markers))
    markers.sort(key=lambda row: (row["source_record_id"], row["opening_start_char"]))
    grouped: dict[str, list[dict[str, Any]]] = {}
    for marker in markers:
        grouped.setdefault(marker["source_record_id"], []).append(marker)

    rows: list[dict[str, Any]] = []
    chapter_counts: Counter[str] = Counter()
    missing_sources: list[str] = []
    for source_id, chapter_markers in grouped.items():
        source_record = source_by_id.get(source_id)
        if source_record is None:
            missing_sources.append(source_id)
        source = (source_record or {}).get("source", {})
        for index, marker in enumerate(chapter_markers):
            rows.append({
                "marker_id": marker["marker_id"],
                "source_record_id": source_id,
                "source_chapter_title": marker.get("source_chapter_title", ""),
                "source_page_url": source.get("page_url", ""),
                "source_revision_id": source.get("page_revision_id", ""),
                "source_text_sha256": marker.get("source_text_sha256", ""),
                "opening_cue": marker.get("opening_cue", ""),
                "opening_start_char": marker["opening_start_char"],
                "opening_end_char": marker["opening_end_char"],
                "previous_opening_start_char": (
                    chapter_markers[index - 1]["opening_start_char"] if index else ""),
                "next_opening_start_char": (
                    chapter_markers[index + 1]["opening_start_char"]
                    if index + 1 < len(chapter_markers) else ""),
                "review_status": "pending",
                "confirmed_narrative_opening": "",
                "story_end_char": "",
                "parent_story_id": "",
                "nesting_depth": "",
                "DIA": "",
                "MOTIF": "",
                "MORAL": "",
                "reviewer_notes": "",
            })
            chapter_counts[source_id] += 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)

    report = {
        "schema": "ansg.kalila_opening_review_queue_report/1",
        "status": "metadata_only_manual_review_queue",
        "candidate_openings": len(rows),
        "source_chapters": len(grouped),
        "candidates_by_source_record_id": dict(sorted(chapter_counts.items())),
        "source_text_embedded": False,
        "neighboring_cue_offsets_are_story_boundaries": False,
        "boundary_and_annotation_fields_prefilled": False,
        "missing_source_records": sorted(missing_sources),
        "review_protocol": [
            "Open the pinned page revision and verify the cue against the extracted source record.",
            "Decide whether the cue introduces a narrative rather than a citation or example.",
            "If confirmed, record a separately reviewed ending offset and parent/resumption evidence.",
            "Leave nesting and DIA/MOTIF/MORAL blank unless a reviewer supplies source evidence.",
            "Keep all chapters from this work in one split group to prevent leakage.",
        ],
        "limitations": [
            "Cue-to-cue spans are navigation aids, not story segmentation.",
            "Offsets are Unicode code-point offsets into the exact extracted chapter text identified by SHA-256.",
            "The queue is not a set of gold labels and contributes zero triple-covered tokens.",
        ],
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    main()
