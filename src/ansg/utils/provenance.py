"""Provenance, hashing and deterministic-run helpers.

Every derived dataset written by ANSG is accompanied by a manifest recording
the exact input file hashes, configuration hash, code version and the *real*
wall-clock time of the run. Manifests are never back-dated: they describe the
run that produced them, not any historical experiment.
"""

from __future__ import annotations

import hashlib
import json
import os
import platform
import random
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable, Mapping

_CHUNK = 1 << 20


def sha256_file(path: str | os.PathLike[str]) -> str:
    """Return the hex SHA-256 digest of a file's bytes."""
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(_CHUNK), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256_text(text: str) -> str:
    """Return the hex SHA-256 digest of UTF-8 encoded text."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def stable_json_dumps(obj: Any) -> str:
    """Canonical JSON (sorted keys, no ASCII escaping) for hashing/serialisation."""
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def config_hash(config: Mapping[str, Any]) -> str:
    """Hash of a configuration mapping, independent of key order."""
    return sha256_text(stable_json_dumps(config))


def git_revision(repo_dir: str | os.PathLike[str] | None = None) -> dict[str, Any]:
    """Return current git commit and dirty flag, or ``unknown`` if unavailable."""
    cwd = str(repo_dir) if repo_dir else None
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=cwd, capture_output=True, text=True, check=True
        ).stdout.strip()
        status = subprocess.run(
            ["git", "status", "--porcelain"], cwd=cwd, capture_output=True, text=True, check=True
        ).stdout
        return {"commit": commit, "dirty": bool(status.strip())}
    except (OSError, subprocess.CalledProcessError):
        return {"commit": "unknown", "dirty": None}


def seed_everything(seed: int) -> None:
    """Seed Python's RNG and, if installed, NumPy and PyTorch.

    Data preprocessing in Phase 1 does not rely on random number generators
    (splits are hash-based), but this helper is provided for later phases.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    try:  # optional dependency
        import numpy as np  # type: ignore[import-not-found]

        np.random.seed(seed)
    except ImportError:
        pass
    try:  # optional dependency
        import torch  # type: ignore[import-not-found]

        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
    except ImportError:
        pass


@dataclass
class RunManifest:
    """Machine-readable record of a single preprocessing/experiment run."""

    run_type: str
    config: Mapping[str, Any]
    inputs: dict[str, str] = field(default_factory=dict)  # path -> sha256
    outputs: dict[str, str] = field(default_factory=dict)  # path -> sha256
    stats: dict[str, Any] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
    started_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    finished_at: str | None = None

    def add_inputs(self, paths: Iterable[str | os.PathLike[str]]) -> None:
        for p in paths:
            self.inputs[str(p)] = sha256_file(p)

    def add_output(self, path: str | os.PathLike[str]) -> None:
        self.outputs[str(path)] = sha256_file(path)

    def finish(self) -> None:
        self.finished_at = datetime.now(timezone.utc).isoformat()

    def to_dict(self) -> dict[str, Any]:
        return {
            "run_type": self.run_type,
            "note": (
                "Generated by the ANSG reimplementation. Timestamps are the real "
                "execution time of this run and do not describe historical experiments."
            ),
            "started_at": self.started_at,
            "finished_at": self.finished_at,
            "git": git_revision(Path(__file__).resolve().parents[3]),
            "python": sys.version.split()[0],
            "platform": platform.platform(),
            "config_sha256": config_hash(self.config),
            "config": self.config,
            "inputs": self.inputs,
            "outputs": self.outputs,
            "stats": self.stats,
            "warnings": self.warnings,
        }

    def write(self, path: str | os.PathLike[str]) -> None:
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(self.to_dict(), fh, ensure_ascii=False, indent=2, sort_keys=True)
            fh.write("\n")
